"""Planning power of the EFFECTIVE design (D8: S = 2) next to the protocol default (S = 4),
with the unchanged planning simulator (twinguard/twinguard_power_sim.py v0.5) and its
scenarios. Illustrative planning only; no study data are read (Astra strategy review,
2026-11-09: "the published S=4 figures do not justify S=2").

  python resource/power_design.py --out results/power_design.md [--simulations 4000]
"""
import argparse
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'twinguard'))
import twinguard_power_sim as PS  # noqa: E402


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--out', required=True)
    ap.add_argument('--simulations', type=int, default=4000)
    ap.add_argument('--seed', type=int, default=20261105)
    a = ap.parse_args(argv)
    rng = np.random.default_rng(a.seed)
    lines = ['# Planning power: effective design S = 2 vs protocol default S = 4',
             '', f'Generated by `resource/power_design.py` with `twinguard_power_sim.py` '
             f'(unchanged), {a.simulations} simulations per cell, seed {a.seed}. Monte Carlo '
             f'95% half-width <= {1.96 * np.sqrt(.25 / a.simulations):.3f}. H1 = P(reject 0 | '
             'A-N = +10 pp, P-N = 0); H1H2 = P(H1 and H2 | A-N = A-P = +10 pp); type1 / equiv '
             'under the average null; t1_sh / eq_sh under the sharp null. Baselines are the '
             'simulator\'s Beta(2.5, 7.5) (mean 25%), NOT the observed floor: these figures do '
             'not describe power at a floor.', '',
             '| Scenario | P x S | Analysis | H1 | H1H2 | type1 | equiv | t1_sh | eq_sh |',
             '|---|---|---|---|---|---|---|---|---|']
    for label, sc in PS.SCENARIOS.items():
        for S in (2, 4):
            r = PS.evaluate(rng, a.simulations, 30, 4, S, sc)
            for meth, v in r.items():
                lines.append(f'| {label} | 4x{S} | {meth} | {v["H1"]:.2f} | {v["H1H2"]:.2f} | '
                             f'{v["type1"]:.3f} | {v["equiv"]:.2f} | {v["type1_sharp"]:.3f} | '
                             f'{v["equiv_sharp"]:.2f} |')
    Path(a.out).write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
